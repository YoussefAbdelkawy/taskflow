// npm run trace: builds docs/TRACEABILITY.md (user story -> tests) from docs/USER_STORIES.md
// and the titles of every test in tests/. A test counts for a story when the story ID
// (e.g. "US7-2") is in its describe / it / test title.
//
//   npm run trace                    fails if a story is not covered by unit/integration AND E2E
//   npm run trace -- --allow-missing writes the matrix but never fails (used in CI during M3)
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const STORIES_FILE = path.join(ROOT, 'docs', 'USER_STORIES.md');
const OUTPUT_FILE = path.join(ROOT, 'docs', 'TRACEABILITY.md');
const TESTS_DIR = path.join(ROOT, 'tests');

const STORY_ROW = /^\|\s*(US\d+-\d+|NFR\d+)\s*\|\s*(FR\d+)\s*\|\s*(\w+)\s*\|/;
const STORY_ID = /\b(?:US\d+-\d+|NFR\d+)\b/g;
// describe('…'), it('…'), test('…'), test.describe('…') and it.each([...])('…')
const TITLE = /(?:\b(?:describe|it|test)(?:\.\w+)?|\]\s*\))\(\s*(['"`])((?:\\.|(?!\1)[\s\S])*?)\1/g;

const listFiles = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return listFiles(full);
    return /\.(test|spec)\.js$/.test(entry.name) ? [full] : [];
  });

/** @returns {{ id, fr, owner }[]} in the order of USER_STORIES.md */
function readStories(markdown) {
  return markdown
    .split('\n')
    .map((line) => STORY_ROW.exec(line))
    .filter(Boolean)
    .map(([, id, fr, owner]) => ({ id, fr, owner }));
}

// Declarative: every story ID that appears in a test title of this source file
const idsInTitles = (source) =>
  new Set(
    [...source.matchAll(TITLE)].flatMap(([, , title]) =>
      [...title.matchAll(STORY_ID)].map(([id]) => id),
    ),
  );

/** @returns {Map<string, { unit: Set, e2e: Set }>} story id -> test files that mention it */
function collectTests(files) {
  const found = new Map();
  // Imperative: record each file once under every story it tests
  for (const file of files) {
    const relative = path.relative(ROOT, file).split(path.sep).join('/');
    const kind = relative.startsWith('tests/e2e/') ? 'e2e' : 'unit';
    for (const id of idsInTitles(fs.readFileSync(file, 'utf8'))) {
      if (!found.has(id)) found.set(id, { unit: new Set(), e2e: new Set() });
      found.get(id)[kind].add(relative);
    }
  }
  return found;
}

// A user story needs both kinds of test; an NFR (performance, reliability…) is proven by
// unit/integration tests alone
const statusOf = ({ unit, e2e }, needsE2e = true) => {
  if (unit.size > 0 && (e2e.size > 0 || !needsE2e)) return '✅';
  if (unit.size > 0 || e2e.size > 0) return '⚠️';
  return '❌';
};

const fileList = (files) =>
  files.size === 0
    ? '—'
    : [...files]
        .sort()
        .map((file) => `\`${file.replace(/^tests\//, '')}\``)
        .join('<br>');

function buildMatrix(stories, found) {
  const empty = { unit: new Set(), e2e: new Set() };
  // Declarative: one table row per story
  const rows = stories.map((story) => {
    const tests = found.get(story.id) ?? empty;
    return { ...story, status: statusOf(tests, story.id.startsWith('US')), tests };
  });
  const lines = rows.map(
    (row) =>
      `| ${row.id} | ${row.fr} | ${row.owner} | ${fileList(row.tests.unit)} | ${fileList(row.tests.e2e)} | ${row.status} |`,
  );
  const covered = rows.filter((row) => row.status === '✅').length;
  const markdown = [
    '# Traceability matrix',
    '',
    'Generated by `npm run trace` from [USER_STORIES.md](USER_STORIES.md) and the test titles. Do not edit by hand.',
    '',
    `✅ unit/integration and E2E · ⚠️ only one kind · ❌ no test yet. Covered: **${covered} of ${rows.length}**.`,
    '',
    '| Story | FR | Owner | Unit and integration tests | E2E tests | Status |',
    '| --- | --- | --- | --- | --- | --- |',
    ...lines,
    '',
  ].join('\n');
  return { markdown, missing: rows.filter((row) => row.status !== '✅') };
}

function main() {
  const stories = readStories(fs.readFileSync(STORIES_FILE, 'utf8'));
  const { markdown, missing } = buildMatrix(stories, collectTests(listFiles(TESTS_DIR)));
  fs.writeFileSync(OUTPUT_FILE, markdown);
  console.log(
    `Wrote docs/TRACEABILITY.md: ${stories.length - missing.length}/${stories.length} covered`,
  );
  if (missing.length > 0) {
    console.log(`Not fully covered: ${missing.map((row) => row.id).join(', ')}`);
    if (!process.argv.includes('--allow-missing')) process.exitCode = 1;
  }
}

if (require.main === module) main();

module.exports = { readStories, collectTests, buildMatrix, statusOf };
